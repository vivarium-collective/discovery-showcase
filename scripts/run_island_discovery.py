#!/usr/bin/env python
"""Bias-isolated agent discovery of an ecological LAW + its generating mechanism.

Island biogeography as a discovery target: can the deployed agent (1) discover the species-area law
S ~ A^z from simulation data and (2) discriminate which known mechanism produced it --- Hubbell
neutral drift vs. MacArthur-Wilson equilibrium --- given that the mere existence of a species-area
relationship does not discriminate them (both produce one)? The agent reads the candidate mechanism
contracts and the observed (area, richness) data; the sealed truth (which mechanism) is withheld.

Data are real, generated by the viva-island-biogeography neutral-vs-equilibrium study
(``python workspace/studies/neutral-vs-equilibrium/sims/run.py`` in that workspace; 12 islands,
area 1-100). This renders the discriminating figure always, and runs the live agent with
``--run-agent`` (via ``claude -p``).
"""
from __future__ import annotations

import argparse
import re
import subprocess
from pathlib import Path

import numpy as np

PAPER = Path.home() / "Desktop" / "PLOS_Discovery_Engine" / "versions" / "v1" / "figures"

AREAS = [1.0, 1.5, 2.3, 3.5, 5.3, 8.1, 12.3, 18.7, 28.5, 43.3, 65.8, 100.0]
DATA = {  # sealed truth -> real (area -> richness) from the workspace study
    "neutral":     [1.44, 1.99, 2.93, 3.65, 5.46, 7.40, 10.38, 14.03, 19.83, 26.87, 35.81, 45.73],
    "equilibrium": [21.67, 22.25, 23.59, 27.89, 27.10, 28.53, 29.15, 33.13, 32.65, 35.88, 37.41, 37.99],
}
CONTRACTS = (
    "- neutral: Hubbell neutral metacommunity. Diversity from dispersal and ecological drift in a "
    "local community whose size J grows with island area; NO colonization/extinction rate asymmetry. "
    "Predicts a STEEP species-area exponent (z ~ 0.5-0.8) and richness that keeps climbing with area.\n"
    "- equilibrium: MacArthur-Wilson (1967). Richness set by area-dependent extinction balanced "
    "against colonization. Predicts a SHALLOW exponent (z ~ 0.1-0.3) and richness that SATURATES.\n"
    "- rescue: MacArthur-Wilson with the Brown & Kodric-Brown rescue effect; even shallower, less turnover."
)


def z_fit(S):
    return float(np.polyfit(np.log(AREAS), np.log(S), 1)[0])


def _prompt(S):
    pairs = ", ".join(f"({a:g},{s:.2f})" for a, s in zip(AREAS, S))
    return ("You are discovering an ecological law from island-biogeography simulation data, then "
            "identifying which known mechanism generated it.\n\n"
            f"Observed (island area, species richness):\n{pairs}\n\n"
            f"Candidate mechanisms and their predictions:\n{CONTRACTS}\n\n"
            "The mere existence of a species-area relationship does NOT discriminate them --- use the "
            "exponent magnitude AND whether richness saturates.\n\n"
            "Reply on ONE line: LAW: S ~ A^z with z=<number>; MECHANISM: <neutral|equilibrium|rescue>; "
            "REASON: <short>.")


def run_agent():
    out = {}
    for truth, S in DATA.items():
        ans = subprocess.run(["claude", "-p", _prompt(S)], capture_output=True, text=True, timeout=180).stdout.strip()
        low = ans.lower()
        mm = re.search(r"mechanism:\s*(neutral|equilibrium|rescue)", low)
        zm = re.search(r"z\s*=\s*([-\d.]+)", low)
        inferred = mm.group(1) if mm else "?"
        z_agent = float(zm.group(1)) if zm else None
        out[truth] = dict(inferred=inferred, correct=inferred == truth, z_true=round(z_fit(S), 3),
                          z_agent=z_agent, answer=ans[:200])
        print(f"  sealed={truth:<12} z_true={z_fit(S):.3f} agent z={z_agent} mech={inferred} "
              f"{'OK' if inferred == truth else 'X'}")
    print(f"  -> law recovered {sum(1 for d in out.values() if d['z_agent'] and abs(d['z_agent']-d['z_true'])<0.25)}/{len(DATA)}, "
          f"mechanism discriminated {sum(1 for d in out.values() if d['correct'])}/{len(DATA)}")
    return out


def figure(out_path):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    fig, ax = plt.subplots(1, 2, figsize=(8.2, 3.1))
    col = {"neutral": "#bc4749", "equilibrium": "#2a6f97"}
    zs = {k: z_fit(v) for k, v in DATA.items()}
    for k, S in DATA.items():
        ax[0].loglog(AREAS, S, "o-", color=col[k], label=f"{k} (z={zs[k]:.2f})", ms=4)
        ax[1].plot(AREAS, S, "o-", color=col[k], ms=4, label=k)
    ax[0].set_xlabel("island area A"); ax[0].set_ylabel("species richness S")
    ax[0].set_title("Species–area law (log–log)", fontsize=10); ax[0].legend(fontsize=8); ax[0].grid(alpha=0.3, which="both")
    ax[1].set_xlabel("island area A"); ax[1].set_ylabel("species richness S")
    ax[1].set_title("Shape: neutral climbs, equilibrium saturates", fontsize=10); ax[1].legend(fontsize=8); ax[1].grid(alpha=0.3)
    fig.suptitle("Island biogeography: both mechanisms give a SAR; exponent + saturation discriminate them", fontsize=10.5)
    fig.tight_layout(rect=(0, 0, 1, 0.94))
    Path(out_path).parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(out_path, bbox_inches="tight"); fig.savefig(Path(out_path).with_suffix(".png"), dpi=120, bbox_inches="tight")
    print(f"saved {Path(out_path).name}  (z: neutral={zs['neutral']:.2f}, equilibrium={zs['equilibrium']:.2f})")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--run-agent", action="store_true", help="run the live agent via claude -p")
    ap.add_argument("--out", default=str(PAPER / "fig_island_discovery.pdf"))
    a = ap.parse_args()
    figure(a.out)
    if a.run_agent:
        print("live bias-isolated agent discovery:")
        run_agent()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
